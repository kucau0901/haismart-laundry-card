#!/usr/bin/env node
// Generates src/model/contract.ts from test/fixtures/entity_contract.json (the haismart entity
// contract for the 0504 twin washer + dryer), and src/sample.ts (the card-picker preview's values)
// from the real decoded snapshot. Only the attributes the card reads are bundled in either.
// Run: npm run gen:contract
import { readFileSync, writeFileSync } from "node:fs";

const KEY_ATTRIBUTES = [
  "laundryCyclePhase", "dryerCyclePhase",
  "washerRunningMode", "dryerRunningMode",
  "remainingTimeHH", "remainingTimeMM", "dryerRemainingDryTime", "dryerRemainingResnTime",
  "remainingAntiCreaseTime",
  "washerUnifiedProgramSettings", "dryerUnifiedProgramSettings",
  "washerMessage", "dryerMessage",
  "washerRemoteCtrValid", "dryerRemoteCtrValid",
  "washerDoorStatus", "dryerDoorStatus", "washerDoorLockStatus", "dryerDoorLockStatus",
  "washerPowerStatus", "dryerPowerStatus", "onOffStatus", "childLockStatus",
  "laundryCycleStatus", "washerDryStatus",
  "remainingDetergentStatus", "remainingSoftenerStatus",
  "washerDryMode", "dryerDryMode",
  "totalWaterUsed", "washerTotalElectricityUsed", "totalWashCycle",
  "currentWaterUsed", "washerCurrentElectricityUsed",
  // The details row: what each drum is running with.
  "washTemp", "spinSpeed", "washerActualWeight",
  "dryerTempLevel", "dryerDryLevel", "dryerWeight",
];

const src = new URL("../test/fixtures/entity_contract.json", import.meta.url);
const out = new URL("../src/model/contract.ts", import.meta.url);
const contract = JSON.parse(readFileSync(src, "utf8"));

const table = {};
for (const key of KEY_ATTRIBUTES) {
  const a = contract.attributes[key];
  if (!a) throw new Error(`entity_contract.json has no attribute ${key}`);
  table[key] = {
    name: a.name,
    control: a.control,
    report: a.report,
    unit: a.unit ?? null,
    options: a.options ?? null,
  };
}

const body = `// GENERATED by scripts/gen-contract.mjs from test/fixtures/entity_contract.json. Do not edit.
/* eslint-disable */

export type ContractControl = "sensor" | "binary_sensor" | "switch" | "select" | "number";

export interface ContractAttribute {
  name: string;
  control: ContractControl;
  report: string;
  unit: string | null;
  options: Record<string, string> | null;
}

export const CONTRACT_TYPEID = ${JSON.stringify(contract.typeid)};

export const CONTRACT: Record<string, ContractAttribute> = ${JSON.stringify(table, null, 2)};

export const CONTRACT_BUTTONS: Record<string, string> = ${JSON.stringify(contract.buttons, null, 2)};
`;
writeFileSync(out, body);
console.log(`wrote ${out.pathname} (${KEY_ATTRIBUTES.length} attributes)`);

const snapshot = JSON.parse(
  readFileSync(new URL("../test/fixtures/snapshot_dryer_running_washer_idle.json", import.meta.url), "utf8"),
);
const sample = {};
for (const key of KEY_ATTRIBUTES) if (key in snapshot) sample[key] = snapshot[key];
const sampleOut = new URL("../src/sample.ts", import.meta.url);
writeFileSync(
  sampleOut,
  `// GENERATED by scripts/gen-contract.mjs from test/fixtures/snapshot_dryer_running_washer_idle.json.
// Do not edit. The card-picker preview's values: only the attributes the card reads.

export const SAMPLE_VALUES: Record<string, unknown> = ${JSON.stringify(sample, null, 2)};
`,
);
console.log(`wrote ${sampleOut.pathname} (${Object.keys(sample).length} attributes)`);
